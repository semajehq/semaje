"""semaje language registry — the shared contract for "which language is this?".

One canonical code per language: ISO 639-3 + ISO 15924 script ("swh_Latn",
"amh_Ethi", "yor_Latn"), plus an optional dialect variant for the few
Omnilingual entries that need one ("ell_Grek_cypr1249", Cypriot Greek). Every service resolves whatever the caller sent
(sw, swa, swh, swh_Latn, sw-KE, "Swahili") through this module, so STT, TTS,
the API, and the browser extension all agree.

languages.json is generated by build.py from the authoritative upstream lists
(Whisper, Omnilingual ASR, MMS-TTS, Piper) and committed. Never hand-edit it.
"""
from __future__ import annotations

import json
import unicodedata
from dataclasses import dataclass, asdict
from functools import lru_cache
from pathlib import Path

REGISTRY_PATH = Path(__file__).resolve().parent / "languages.json"


# Regions that imply a non-default script (zh-TW → Traditional Chinese).
REGION_SCRIPT = {
    ("cmn", "TW"): "Hant", ("cmn", "HK"): "Hant", ("cmn", "MO"): "Hant",
    ("yue", "CN"): "Hans", ("srp", "ME"): "Latn",
}


class UnknownLanguage(ValueError):
    status = 400
    code = "unknown_language"


@dataclass(frozen=True)
class Language:
    code: str            # canonical, e.g. "swh_Latn"
    iso3: str
    script: str
    name: str
    iso1: str | None     # ISO 639-1 when one exists, e.g. "sw"
    whisper: str | None  # Whisper's code when Whisper supports the language
    omnilingual: bool    # Omnilingual ASR recognizes it
    mms_tts: str | None  # MMS-TTS model id suffix ("swh", "azj-script_latin") when available
    piper: tuple = ()    # Piper voice keys for this language
    aliases: tuple = ()  # other names/codes people use: "Kikuyu", "Farsi", macro codes like "swa"
    variant: str | None = None  # dialect tag for ell_Grek_cypr1249-style codes

    def to_dict(self) -> dict:
        d = asdict(self)
        d["mmsTts"] = d.pop("mms_tts")
        d["piper"] = list(self.piper)
        d["aliases"] = list(self.aliases)
        return d

    @staticmethod
    def from_row(row: dict) -> "Language":
        return Language(
            code=row["code"], iso3=row["iso3"], script=row["script"], name=row["name"],
            iso1=row.get("iso1"), whisper=row.get("whisper"), omnilingual=bool(row.get("omnilingual")),
            mms_tts=row.get("mmsTts"), piper=tuple(row.get("piper") or ()),
            aliases=tuple(row.get("aliases") or ()), variant=row.get("variant"),
        )


def fold(text: str) -> str:
    text = unicodedata.normalize("NFKD", text)
    return "".join(c for c in text if not unicodedata.combining(c)).strip().lower()


class Registry:
    def __init__(self, languages: list[Language]):
        self.languages = languages
        self._by_key: dict[str, Language] = {}
        # Precedence: canonical codes, then Whisper/ISO aliases, then names.
        # For a bare iso3 with several scripts, the first listed entry wins;
        # build.py orders the most widely used script first.
        for lang in languages:
            self._add(lang.code, lang)
        for lang in languages:
            if lang.variant:  # bare iso3/iso1 must resolve to the base language, not a dialect
                continue
            for key in (lang.whisper, lang.iso1, lang.iso3, lang.mms_tts):
                if key:
                    self._add(key, lang)
        for lang in languages:  # variant-only languages (roh, lld) still resolve by bare code
            if lang.variant:
                for key in (lang.iso1, lang.iso3, f"{lang.iso3}_{lang.script}"):
                    if key:
                        self._add(key, lang)
        for lang in languages:
            self._add(lang.name, lang)
        for lang in languages:
            for alias in lang.aliases:
                self._add(alias, lang)
        self._by_whisper = {lang.whisper: lang for lang in languages if lang.whisper}
        self._by_code = {lang.code: lang for lang in languages}

    def _add(self, key: str, lang: Language) -> None:
        self._by_key.setdefault(fold(key), lang)

    def get(self, code: str) -> Language | None:
        return self._by_code.get(code)

    def resolve(self, value: str | None) -> Language | None:
        """sw / swa / swh / swh_Latn / sw-KE / Swahili → Language. None, '' or 'auto' → None."""
        if value is None:
            return None
        raw = value.strip()
        if raw == "" or raw.lower() == "auto":
            return None
        for key in (fold(raw), fold(raw.replace("-", "_"))):
            if key in self._by_key:
                return self._by_key[key]
        # BCP-47 with region/script subtags: sw-KE, zh-Hant-TW, zh-TW, yo_NG.
        parts = [p for p in raw.replace("_", "-").split("-") if p]
        base = self._by_key.get(fold(parts[0]))
        if base is not None:
            script = next((p.title() for p in parts[1:] if len(p) == 4 and p.isalpha()), None)
            if script is None:
                region = next((p.upper() for p in parts[1:] if len(p) == 2), None)
                script = REGION_SCRIPT.get((base.iso3, region))
            if script:
                return self._by_code.get(f"{base.iso3}_{script}", base)
            return base
        raise UnknownLanguage(f"Unknown language {value!r}. GET /languages lists every supported code.")

    def from_whisper(self, code: str | None) -> Language | None:
        return self._by_whisper.get(code or "")


@lru_cache(maxsize=1)
def registry() -> Registry:
    data = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    return Registry([Language.from_row(row) for row in data["languages"]])


__all__ = ["Language", "Registry", "UnknownLanguage", "registry", "fold"]
